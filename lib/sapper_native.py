def cleanup_bridge(directory):
    """Undo only the Web-owned import left after the original teardown."""
    directory = Path(directory).resolve()
    claude = directory / "CLAUDE.md"
    bridge = directory / ".claude/sapper-workspace.md"
    if claude.is_file() and claude.resolve().is_relative_to(directory):
        original = claude.read_text()
        updated = re.sub(r"<!-- sapper-workspace:start -->.*?<!-- sapper-workspace:end -->\n?", "", original, flags=re.S)
        if updated != original:
            claude.write_text(updated)
    if bridge.is_file() and bridge.resolve().is_relative_to(directory) and bridge.read_text().startswith("<!-- generated by sapper web -->"):
        bridge.unlink()


class NativeError(sapper.FGError):
    def __init__(self, message, status=400):
        super().__init__(message)
        self.status = status


def parsers():
    root = sapper.build_parser()
    action = next(a for a in root._actions if isinstance(a, argparse._SubParsersAction))
    return {k: v for k, v in action.choices.items() if k not in EXCLUDED}


class NativeSurface:
    def __init__(self, app):
        self.app = app

    def catalog(self):
        commands = []
        for name, parser in parsers().items():
            fields = []
            for a in parser._actions:
                if isinstance(a, argparse._HelpAction) or (name == "flag" and a.dest == "submit"):
                    continue
                flag = next((o for o in a.option_strings if o.startswith("--")), None)
                kind = "boolean" if isinstance(a, (argparse._StoreTrueAction, argparse._StoreFalseAction)) else "integer" if a.type is int else "text"
                repeated = isinstance(a, argparse._AppendAction) or a.nargs in ("*", "+")
                fields.append({"name": a.dest, "label": FIELD_LABELS.get(a.dest, a.dest), "flag": flag,
                               "type": kind, "repeated": repeated, "nargs": a.nargs,
                               "required": a.required, "choices": list(a.choices) if a.choices else None,
                               "default": a.default, "help": a.help or ""})
            commands.append({"name": name, "label": LABELS.get(name, name), "help": parser.description or "",
                             "fields": fields})
        return {"version": sapper.__version__, "commands": commands, "excluded": ["arena", "bench", "flag --submit"],
                "roots": [str(p) for p in self.app.workspace_roots], "kb_root": str(KnowledgeBase.default_root())}

    def allowed_path(self, value, cwd, *, kb=False):
        path = Path(value).expanduser()
        path = (cwd / path).resolve() if not path.is_absolute() else path.resolve()
        roots = self.app.workspace_roots + ([KnowledgeBase.default_root()] if kb else [])
        if not any(path.is_relative_to(root.resolve()) for root in roots) or path.is_relative_to(self.app.state):
            raise NativeError("原生功能文件路径不在已选工作区范围；请先在网页绑定相应目录", 403)
        return path

    def prepare(self, pid, data):
        name = data.get("operation")
        available = parsers()
        if name not in available:
            raise NativeError("该命令不在本轮非平台原生功能范围内")
        if pid == "global":
            if name != "kb":
                raise NativeError("全局入口仅用于原生知识库；其他命令请选择工作区")
            project = {"id": "global", "name": "全局知识库", "path": str(self.app.root), "goal": "原生共享知识库"}
        else:
            project = self.app.project(pid)
        cwd = Path(project["path"])
        if pid != "global":
            self.app.inside(cwd / ".sapper", cwd)
        if name in ("setup", "teardown"):
            for rel in (".claude", ".claude/settings.json", "AGENTS.md", "CLAUDE.md"):
                self.app.inside(cwd / rel, cwd)
        fields = next(c["fields"] for c in self.catalog()["commands"] if c["name"] == name)
        values = data.get("values", {})
        if not isinstance(values, dict) or set(values) - {f["name"] for f in fields}:
            raise NativeError("参数不正确；平台提交参数不受支持")
        optional, positional = [], []
        for f in fields:
            value = values.get(f["name"])
            if value is None or value == "" or value == [] or value is False:
                continue
            if f["type"] == "boolean":
                if type(value) is not bool:
                    raise NativeError(f"{f['label']} 必须为布尔值")
                optional.append(f["flag"])
                continue
            sequence = value if f["repeated"] and isinstance(value, list) else [value]
            if not f["repeated"] and isinstance(value, (list, dict)):
                raise NativeError(f"{f['label']} 参数不正确")
            for item in sequence:
                if type(item) not in (str, int) or "\x00" in str(item) or len(str(item)) > 100000:
                    raise NativeError(f"{f['label']} 必须为文本或整数")
                if f["type"] == "integer":
                    try:
                        item = str(int(item))
                    except (TypeError, ValueError) as exc:
                        raise NativeError(f"{f['label']} 必须为整数") from exc
                if f["flag"]:
                    optional.append(f["flag"] + "=" + str(item))
                else:
                    positional.append(str(item))
        argv = [name] + optional + (["--"] + positional if positional else [])
        # Use the actual parser; suppress argparse's process-exiting error path.
        parser = sapper.build_parser()
        parser.error = lambda message: (_ for _ in ()).throw(NativeError(message))
        for child in next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction)).choices.values():
            child.error = parser.error
        args = parser.parse_args(["--store", str(cwd / ".sapper"), *argv])
        if getattr(args, "submit", False):
            raise NativeError("本轮只提供本地 Flag 记账，不进行平台提交")
        # Path arguments retain CLI semantics but stay within explicitly permitted roots.
        for field in ("root", "templates", "doc_file", "set_file", "detail_file", "path", "file", "fleet_file", "out", "channel"):
            value = getattr(args, field, None)
            if value:
                self.allowed_path(value, cwd, kb=name == "kb")
        if name == "kb" and args.action == "import":
            if not (args.path or args.target):
                raise NativeError("请选择 Markdown 导入文件或目录")
            self.allowed_path(args.path or args.target, cwd)
        if name in ("command", "sweep"):
            root = self.allowed_path(args.root, cwd)
            for graph in root.glob("*/.sapper/project.json"):
                self.allowed_path(str(graph), cwd)
        fleet_config = None
        if name == "command":
            file = self.allowed_path(args.fleet_file or "fleet.json", cwd)
            try:
                fleet_config = sapper._fleet_load(file) if file.exists() else {}
            except sapper.FGError:
                fleet_config = {}  # Original commander falls back on invalid/missing files.
            fleet_config.setdefault("session", "sapper-fleet")
            fleet_config.setdefault("root", args.root)
            self.allowed_path(fleet_config["root"], cwd)
        if name == "fleet" and args.action != "init":
            file = self.allowed_path(args.file, cwd)
            fleet_config = sapper._fleet_load(file) if file.exists() or args.action in ("up", "down", "status") else {"session": "sapper-fleet", "root": "runs"}
            self.allowed_path(fleet_config.get("root", "runs"), cwd if args.action == "hire" else file.parent)
        destructive = (name in ("init", "setup") and args.force) or name == "teardown" or (name == "fleet" and args.action in ("down", "fire"))
        argv = [sys.executable, str(Path(sapper.__file__).resolve()), "--store", str(cwd / ".sapper"), *argv]
        profile_id = data.get("profile_id") or ""
        profile = next((p for p in self.app.profiles() if p["id"] == profile_id), None)
        if profile_id and not profile:
            raise NativeError("模型配置不存在", 409)
        payload = {"argv": argv, "cwd": str(cwd), "profile_id": profile_id, "profile": profile, "fleet_config": fleet_config}
        digest = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
        return {**payload, "command": shlex.join(argv), "preview_token": digest, "destructive": bool(destructive),
                "operation": name, "needs_hooks": name in ("auto", "dispatch", "command", "sweep") or (name == "fleet" and args.action in ("up", "hire"))}

    def execute(self, pid, data):
        if data.get("operation") == "teardown":
            self.prepare(pid, data)
            project = self.app.project(pid)
            self.app.workspaces.bind({"path": project["path"], "goal": project["goal"], "name": project["name"]})
        with self.app.workspaces.lifecycle():
            return self._execute(pid, data)

    def _execute(self, pid, data):
        prepared = self.prepare(pid, data)
        if data.get("preview_token") != prepared["preview_token"]:
            raise NativeError("参数已改变，请重新预览原命令", 409)
        if prepared["destructive"] and data.get("acknowledged") is not True:
            raise NativeError("此操作会撤销接入、覆盖数据或停止编队，请先确认预览中的目标", 409)
        env = {"SAPPER_TMUX_SOCKET": self.app.tmux_socket or "", "SAPPER_WEB_STATE": str(self.app.state),
               "SAPPER_WORKSPACE_ID": pid, "SAPPER_NATIVE_OPERATION": prepared["operation"]}
        if data.get("request_id"):
            existing = next((r for r in self.app.runs(pid) if r.get("request_id") == data["request_id"]), None)
            if existing:
                return existing
        actor = None
        if prepared["operation"] in ("auto", "dispatch", "command", "sweep") and not data.get("values", {}).get("dry_run"):
            role = "commander" if prepared["operation"] in ("command", "sweep") else "worker"
            if prepared["operation"] == "dispatch":
                role = "verifier" if data.get("values", {}).get("target") == "verify" else "commander" if data.get("values", {}).get("target") in ("reason", "brainstorm", "blindspot") else "worker"
            aid = uuid.uuid4().hex[:16]
            actor = {"id": aid, "workspace_id": pid, "workspace_scope": [pid], "role": role,
                     "role_source": "original-cli-operation", "name": "原生 " + prepared["operation"],
                     "parent_agent_id": None, "claude_session_id": None, "execution_mode": "cli", "cwd": prepared["cwd"],
                     "mission": prepared["command"], "profile_id": prepared["profile_id"],
                     "profile_name": prepared["profile"]["name"] if prepared["profile"] else "继承原环境",
                     "created_at": sapper.now_iso(), "desired_state": "running", "run_ids": [],
                     "native_operation": prepared["operation"], "native_request": {k: data.get(k) for k in ("operation", "values", "profile_id")}}
            self.app.workspaces.save_agent(actor)
            env["SAPPER_AGENT_ID"] = aid
        try:
            run = self.app.start(pid, {"kind": "native-cli", "profile_id": prepared["profile_id"],
                                   "request_id": data.get("request_id")}, native={"argv": prepared["argv"],
                                   "cwd": prepared["cwd"], "env": env, "native_operation": prepared["operation"],
                                   "skip_hook_install": not prepared["needs_hooks"],
                                   **({"agent_id": actor["id"], "role": actor["role"]} if actor else {}),
                                   **({"project_override": {"id": "global", "name": "全局知识库", "path": str(self.app.root)}} if pid == "global" else {})})
        except Exception:
            if actor:
                actor["desired_state"] = "stopped"
                self.app.workspaces.save_agent(actor)
            raise
        if actor:
            actor.update(run_id=run["id"], run_ids=[run["id"]])
            self.app.workspaces.save_agent(actor)
        return run

    def config_file(self, pid, relative):
        if not isinstance(relative, str):
            raise NativeError("请选择配置文件")
        path = Path(relative)
        if path.is_absolute() or ".." in path.parts or ".sapper" in path.parts or not (path.suffix == ".json" or (len(path.parts) == 2 and path.parts[0] == "templates" and path.suffix == ".md")):
            raise NativeError("此编辑器只管理编队 JSON 和 templates/*.md，不直接修改图", 403)
        return self.app.file(pid, relative)

    def read_config(self, pid, relative):
        path = self.config_file(pid, relative)
        if path.exists():
            if path.stat().st_size > 1024 * 1024:
                raise NativeError("配置文件超过 1 MiB")
            content = path.read_text()
        elif str(relative).startswith("templates/"):
            source = sapper._skill_root() / relative
            content = source.read_text() if source.exists() else ""
        else:
            content = json.dumps({**sapper.FLEET_TEMPLATE, "session": "sapper-fleet-" + pid[:8],
                                  "root": str(self.app.root), "deadline": "",
                                  "panes": [{"name": "board", "type": "shell", "command": "sapper status"}]}, ensure_ascii=False, indent=2)
        return {"path": relative, "content": content, "exists": path.exists(),
                "version": hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else None}

    def save_config(self, pid, data):
        path = self.config_file(pid, data.get("path"))
        content = data.get("content")
        if not isinstance(content, str) or len(content.encode()) > 1024 * 1024 or "\x00" in content:
            raise NativeError("配置内容不正确")
        with self.app.config_lock():
            actual = hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else None
            if "version" not in data or actual != data["version"]:
                raise NativeError("配置已被更新，请重新读取后保存", 409)
            if path.suffix == ".json":
                try:
                    cfg = json.loads(content)
                    if not isinstance(cfg, dict) or not isinstance(cfg.get("session"), str) or not isinstance(cfg.get("panes"), list) or not cfg["panes"]:
                        raise ValueError()
                except (ValueError, TypeError) as exc:
                    raise NativeError("fleet.json 需要 session 和非空 panes 列表") from exc
                self.allowed_path(cfg.get("root", "runs"), path.parent)
            path.parent.mkdir(parents=True, exist_ok=True)
            if path.suffix == ".md":
                # A partial override directory would shadow the entire built-in
                # template set. Seed missing originals without replacing user files.
                for source in (sapper._skill_root() / "templates").glob("*.md"):
                    destination = path.parent / source.name
                    try:
                        with destination.open("x") as file:
                            file.write(source.read_text())
                    except FileExistsError:
                        pass
            fd, temporary = tempfile.mkstemp(prefix=".native-", dir=path.parent)
            try:
                with os.fdopen(fd, "w") as file:
                    file.write(content)
                    file.flush()
                    os.fsync(file.fileno())
                os.replace(temporary, path)
            finally:
                if os.path.exists(temporary):
                    os.unlink(temporary)
        self.app.audit("native.config.saved", project=pid, path=data["path"])
        return self.read_config(pid, data["path"])
